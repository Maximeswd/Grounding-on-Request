#!/usr/bin/env python
"""NO PARTIAL COLUMNS: an arm appears here only if every model x dataset x word cell exists.
Dropped 2026-09-13 for incomplete coverage -- Neo+VGM and PT+APO have no Ground-CF runs at
all, and Neo+CTM+SN (SN = 15% slot negatives, a data augmentation, not an objective) covers
7 of 16 cells. A column of dashes invites the reader to compare means that do not share a
denominator.
THE BIG TABLE, one per model: columns = every interface in the grid (baselines, all LoRA ranks,
prompt tuning with every objective, neologisms with every objective, plus the slot-negative recipe
variants), rows = dataset x modality word x {accuracy, flip, stay}. Bold = best across interfaces in
the row (ties within .005 all bolded). Also a winner tally per interface (how many rows it wins, per
metric and word) banked to results/big_table_winners.json for the conclusions.
Reads results/master_grid.json at the L=5 parity setting (LoRA and baselines have no L).
Writes paper/iclr2027/tables/tab_big_<model>.tex. Usage: python scripts/make_big_table.py
"""
import json, os, sys, collections
# --ood (2026-09-13): read results/master_grid_ood.json and write tab_big_<model>_ood.tex
# plus results/big_table_winners_ood.json; default is the in-distribution grid.
OOD = "--ood" in sys.argv
SFX = "_ood" if OOD else ""
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper", "iclr2027", "tables")
DS = [("vcf", "VCF"), ("color", "ColorSwap"), ("coco", "COCO-CF"), ("groundcf", "Ground-CF")]
MOD = [("gemma3", "Gemma-3-4B"), ("qwen4b", "Qwen-3.5-4B"), ("qwen2b", "Qwen-3.5-2B"), ("e4b", "Gemma-4-E4B")]
WORDS = [("look", "\\lk{}"), ("read", "\\rdw{}")]
METRICS = [("R", "Acc."), ("G", "Flip"), ("Sc", "Stay")]   # Stay = conjunctive (correct AND unchanged) since 2026-09-14
# column order and printed names; a column is dropped for a model if it has no cell at all
# SN = slot negatives: a fraction of training items carry a filler word in the request slot with an
# "unknown operator" target, so the word must be RECOGNISED rather than merely present. It is a data
# axis, not an objective.
# 2026-09-17: this list was broken. A trailing comment after "Neo+SN" swallowed the ("word+apo|5",
# "Neo+APO") entry and ate the comma before it, so the module raised TypeError on import and the four
# per-model grids in the paper were last generated on 2026-09-14 -- BEFORE the Ground-CF harvest
# contamination fix of 2026-09-16. Keep every comment ABOVE the list.
COLS = [("noop|None", "No req."), ("instr|None", "Instr."),
        ("pt|5", "PT"), ("pt+apo|5", "PT+APO"), ("pt+ctm|5", "PT+CTM"), ("pti|5", "PT ins."),
        ("lora_r1|None", "LoRA r1"), ("lora_r4|None", "LoRA r4"), ("lora_r16|None", "LoRA r16"), ("lora_r64|None", "LoRA r64"),
        ("word_sft|5", "Neo"), ("word+v3|5", "Neo+SN"), ("word+apo|5", "Neo+APO"),
        ("word+ctm|5", "Neo+CTM")]
F = lambda v: "--" if v is None else (f"{v:.2f}".lstrip("0") if 0 < v < 1 else f"{v:.2f}")


def main():
    g = json.load(open(f"{ROOT}/results/master_grid{SFX}.json"))
    winners = collections.defaultdict(lambda: collections.Counter())
    for m, mlab in MOD:
        cols = [(k, lab) for k, lab in COLS if any(f"{ds}|{m}|{k}" in g for ds, _ in DS)]
        head = ["% AUTO-GENERATED by scripts/make_big_table.py from results/master_grid.json -- do not edit",
                f"% {mlab}: rows = dataset x word x metric; bold = best across interfaces in the row" + (" (OUT OF DISTRIBUTION split)" if OOD else ""),
                "% italics: inserted PT on Ground-CF equals PT by construction (flag is a no-op there)",
                "\\begin{tabular}{lll" + "c" * len(cols) + "}", "\\toprule",
                "Dataset & Word & Metric & " + " & ".join(lab for _, lab in cols) + " \\\\", "\\midrule"]
        body = []
        for ds, dl in DS:
            for w, wl in WORDS:
                for k, klab in METRICS:
                    field = "R.looktwin" if (ds, k, w) == ("groundcf", "R", "look") else f"{k}.{w}"
                    vals = [(g.get(f"{ds}|{m}|{key}") or {}).get(field) for key, _ in cols]
                    # inserted PT is byte-identical to PT on Ground-CF (the flag is a no-op in the
                    # single-request template; master_grid.py drops those runs), so print PT's value
                    # in italics rather than an empty cell; it never competes for bold.
                    na = [key == "pti|5" and ds == "groundcf" for key, _ in cols]
                    pt_v = (g.get(f"{ds}|{m}|pt|5") or {}).get(field)
                    present = [v for v in vals if v is not None]
                    best = max(present) if present else None
                    cells = []
                    for (key, lab), v, isna in zip(cols, vals, na):
                        if isna:
                            cells.append(f"\\textit{{{F(pt_v)}}}")
                            continue
                        t = F(v)
                        if v is not None and best is not None and v >= best - .005:
                            t = f"\\textbf{{{t}}}"
                            winners[f"{k}|{w}"][lab] += 1
                        cells.append(t)
                    lead = f"{dl if (w == 'look' and k == 'R') else ''} & {wl if k == 'R' else ''} & {klab}"
                    body.append(f"{lead} & " + " & ".join(cells) + " \\\\")
                body.append("\\addlinespace[2pt]")
            body.append("\\addlinespace[4pt]")
        open(f"{OUT}/tab_big_{m}{SFX}.tex", "w").write("\n".join(head + body + ["\\bottomrule", "\\end{tabular}"]) + "\n")
        print(f"[saved] tab_big_{m}{SFX}.tex  ({len(cols)} interfaces)")
    json.dump({"note": "rows won (best across interfaces, ties within .005) summed over 4 models x 4 datasets, per metric|word",
               "wins": {k: dict(v) for k, v in winners.items()}},
              open(f"{ROOT}/results/big_table_winners{SFX}.json", "w"), indent=1)
    for k, v in winners.items():
        print(f"  {k:8s} " + ", ".join(f"{lab} {n}" for lab, n in v.most_common(6)))


if __name__ == "__main__":
    main()
