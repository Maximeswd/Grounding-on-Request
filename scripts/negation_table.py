#!/usr/bin/env python
"""ZERO-SHOT NEGATION over a learned modality word (2026-09-17).

Question: the model has learned that <read> means "answer from the caption". Can its own language
machinery scope a negation over a token that was never in pretraining? The prompt
    Caption: "...". Do not give me a <look_ctrl_0..4> answer.
is a minimal edit of the training template ("Give me a {op} answer."), so a null result cannot be
blamed on a phrasing shift. The target is left implicit: with two sources, not-the-image means the
caption, and drawing that inference is the thing being tested.

Four cells per (benchmark, model), all frame-matched so carrier and polarity are separable:
    word,    positive   the plain training request      (re-run in the same wave, same ckpt)
    word,    negative   "Do not give me a <other> answer."
    English, positive   "Give me a caption-based answer."
    English, negative   "Do not give me an image-based answer."
plus the English pair on the FROZEN model, which says whether negation works at all before training.

Read the sign carefully. Accuracy near the positive ceiling means the negation was understood.
Accuracy near 1-ceiling means the model routed TO the negated source, i.e. it matched on the word's
presence and ignored "Do not" -- the predicted failure mode, since the negated prompt still contains
the other source's word. Accuracy near .50 means the request did nothing.

Writes results/negation_zeroshot.json and paper/iclr2027/tables/tab_negation.tex.
"""
import json, os, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DS = [("color", "ColorSwap"), ("coco", "COCO-CF")]
MOD = [("", "Gemma-3-4B"), ("_qwen35", "Qwen-3.5-4B"), ("_qwen2b", "Qwen-3.5-2B"), ("_gemma4e4b", "Gemma-4-E4B")]
SPLIT = "test_ood"


def load(run, ds, tag):
    f = os.path.join(ROOT, "runs", run, "eval", f"{ds}_{SPLIT}", f"flip_ll{tag}_step_800.json")
    return json.load(open(f)) if os.path.exists(f) else None


def main():
    bank = {"note": __doc__.split("Writes")[0].strip(), "split": SPLIT, "cells": {}}
    rows = []
    for ds, dl in DS:
        for s, ml in MOD:
            neo, fz = f"{ds}_neo_ctrl_5tok_ctm_seed0{s}", f"{ds}_base_frozen_0tok_none_seed0{s}"
            got = {"word_pos": load(neo, ds, "_pos_word"),
                   "word_neg": load(neo, ds, "_neg_word"),
                   "eng_pos": load(neo, ds, "_pos_english"),
                   "eng_neg": load(neo, ds, "_neg_english"),
                   "frozen_eng_pos": load(fz, ds, "_pos_english"),
                   "frozen_eng_neg": load(fz, ds, "_neg_english")}
            cell = {}
            for k, d in got.items():
                if d is None:
                    cell[k] = None; continue
                cell[k] = {"read_acc": d.get("read_acc"), "look_acc": d.get("look_acc"),
                           "read_flip": d.get("read_flip"), "look_flip": d.get("look_flip"),
                           "n": d.get("n")}
            bank["cells"][f"{ds}|{ml}"] = cell
            rows.append((dl, ml, cell))
    have = sum(1 for _, _, c in rows if c.get("word_neg"))
    print(f"  cells with the negated-word eval banked: {have} of {len(rows)}")
    # the LaTeX table is written only for the cells that exist; missing ones print as --
    def f(c, k, m):
        v = (c.get(k) or {}).get(m)
        return "--" if v is None else f"{v:.2f}".lstrip("0")
    lines = [r"% AUTO-GENERATED by scripts/negation_table.py -- do not edit",
             r"\begin{tabular}{llcccccc}", r"\toprule",
             r"& & \multicolumn{2}{c}{word} & \multicolumn{2}{c}{English} & \multicolumn{2}{c}{English, no training} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
             r"Benchmark & Model & positive & negated & positive & negated & positive & negated \\",
             r"\midrule"]
    last = None
    for dl, ml, c in rows:
        d0 = dl if dl != last else ""
        last = dl
        lines.append(f"{d0} & {ml} & {f(c,'word_pos','read_acc')} & {f(c,'word_neg','read_acc')} & "
                     f"{f(c,'eng_pos','read_acc')} & {f(c,'eng_neg','read_acc')} & "
                     f"{f(c,'frozen_eng_pos','read_acc')} & {f(c,'frozen_eng_neg','read_acc')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(f"{ROOT}/paper/iclr2027/tables", exist_ok=True)
    open(f"{ROOT}/paper/iclr2027/tables/tab_negation.tex", "w").write("\n".join(lines) + "\n")
    json.dump(bank, open(f"{ROOT}/results/negation_zeroshot.json", "w"), indent=1)
    print(f"  wrote paper/iclr2027/tables/tab_negation.tex and results/negation_zeroshot.json")
    print("  (accuracy is for the CAPTION request: under a negated frame it is "
          "'gave the caption value when told not to use the image'; chance is .50)")


if __name__ == "__main__":
    main()
