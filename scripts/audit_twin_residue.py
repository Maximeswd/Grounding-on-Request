#!/usr/bin/env python
"""Ground-CF image-twin residue audit (v1.189, 2026-09-25). CPU only, read-only (writes only results/ and, with
--write_clean, a NEW image directory; nothing existing is modified).

Finding: scripts/clevr3_image_twins.py erases the target with d.rectangle([x0, y0, x1 - 1, y1 - 1]) and recolours with
range(x0, x1) / range(y0, y1), but prepare_clevr3.draw() fills INCLUSIVE bounds [cx - r, cx + r]. The last column and
the last row of the target's bbox are therefore never erased / recoloured: every colour and object twin keeps a 1-px
line of the OLD object along its right and bottom edges wherever the old silhouette touches them (a full line for a
square; the bottom line for a triangle; single tip pixels for a circle or a diamond). Count and spatial twins
(scripts/clevr3_twins_count_spatial.py) are full re-renders and are checked here too.

For every pair this regenerates the twin with INCLUSIVE bounds (same new value, same centre/radius/colour) and counts
the pixels in which the shipped twin differs from the clean one. Reports, per split x skill x original value, the share
of twins with any residue and with a visible line (>= 20 px). --write_clean DIR saves the clean twins and a pairs file
with ctx_b pointing at them (pairs_look_all_<split>_clean.jsonl), for a re-evaluation.
Usage: python scripts/audit_twin_residue.py [--write_clean data/clevr3/images_twin_clean]
"""
import argparse, collections, json, os, sys
from PIL import Image, ImageDraw, ImageChops
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from prepare_clevr3 import PALETTE, draw  # noqa: E402
from clevr3_image_twins import nearest, BG  # noqa: E402

SPLITS = {"test_id": "id", "test_ood": "ood", "train": "train"}


def clean_twin(im, skill, bb, old, new):
    im = im.copy()
    x0, y0, x1, y1 = [int(round(v)) for v in bb]
    x0, y0 = max(0, x0), max(0, y0); x1, y1 = min(im.width - 1, x1), min(im.height - 1, y1)
    px = im.load()
    if skill == "color":
        tgt, rep = PALETTE[old], PALETTE[new]
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                nm, d = nearest(px[x, y], PALETTE)
                if nm == old and d < 900:
                    px[x, y] = rep
        return im
    cnt = collections.Counter()
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            nm, d = nearest(px[x, y], PALETTE)
            if d < 900:
                cnt[nm] += 1
    colour = cnt.most_common(1)[0][0]
    # the original generator's centre and radius, so the new silhouette is exactly the shipped one
    X1, Y1 = [int(round(v)) for v in bb][2:]
    cx, cy = (x0 + X1) // 2, (y0 + Y1) // 2
    r = max(6, min(X1 - x0, Y1 - y0) // 2)
    d = ImageDraw.Draw(im)
    d.rectangle([x0, y0, x1, y1], fill=BG)
    draw(d, new, cx, cy, r, PALETTE[colour])
    return im


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--write_clean", default="")
    a = ap.parse_args()
    bank, md = {}, ["# Ground-CF image-twin residue audit", "", "Generated by `scripts/audit_twin_residue.py`. Residue = pixels in "
                    "which the shipped twin differs from a twin regenerated with inclusive bounds.", "",
                    "| split | skill | twins | any residue | visible line (≥ 20 px) | median px | by original value (visible / n) |",
                    "|---|---|---|---|---|---|---|"]
    for split, tag in SPLITS.items():
        pf = os.path.join(ROOT, "data", "clevr3", f"pairs_look_all_{tag}.jsonl")
        if not os.path.exists(pf):
            continue
        rows = {json.loads(l)["id"]: json.loads(l) for l in open(os.path.join(ROOT, "data", "clevr3", f"{split}.jsonl"))}
        per = collections.defaultdict(list); byval = collections.defaultdict(lambda: collections.defaultdict(list))
        clean_rows = []
        for l in open(pf):
            p = json.loads(l); sk = p["skill"]
            A = Image.open(os.path.join(ROOT, p["ctx_a"]["image"])).convert("RGB")
            B = Image.open(os.path.join(ROOT, p["ctx_b"]["image"])).convert("RGB")
            if sk in ("color", "object"):
                it = rows.get(p["id"]); bb = (it or {}).get("bbox")
                if not bb:
                    continue
                C = clean_twin(A, sk, bb, str(p["gold_a"]), str(p["gold_b"]))
                diff = ImageChops.difference(B, C).convert("L")
                npx = sum(1 for v in diff.getdata() if v > 8)
                if a.write_clean and split != "train":
                    od = os.path.join(ROOT, a.write_clean); os.makedirs(od, exist_ok=True)
                    dst = os.path.join(od, os.path.basename(p["ctx_b"]["image"])); C.save(dst)
                    q = json.loads(l); q["ctx_b"] = {"image": os.path.relpath(dst, ROOT)}; q["residue_px_fixed"] = npx
                    clean_rows.append(q)
            else:
                npx = 0                                        # full re-render: no in-place edit to leave residue
                if a.write_clean and split != "train":
                    clean_rows.append(json.loads(l))
            per[sk].append(npx); byval[sk][str(p["gold_a"])].append(npx)
        for sk, v in sorted(per.items()):
            n = len(v); anyr = sum(1 for x in v if x > 0); vis = sum(1 for x in v if x >= 20); med = sorted(v)[n // 2]
            bv = "; ".join(f"{k} {sum(1 for x in xs if x >= 20)}/{len(xs)}" for k, xs in sorted(byval[sk].items()))
            bank[f"{split}|{sk}"] = {"n": n, "any": anyr, "visible": vis, "median_px": med,
                                     "by_value": {k: [sum(1 for x in xs if x >= 20), len(xs)] for k, xs in byval[sk].items()}}
            md.append(f"| {split} | {sk} | {n} | {anyr} ({anyr / n:.0%}) | {vis} ({vis / n:.0%}) | {med} | {bv} |")
        if clean_rows:
            with open(os.path.join(ROOT, "data", "clevr3", f"pairs_look_all_{tag}_clean.jsonl"), "w") as f:
                for q in clean_rows:
                    f.write(json.dumps(q) + "\n")
    json.dump(bank, open(os.path.join(ROOT, "results", "twin_residue_audit.json"), "w"), indent=1)
    open(os.path.join(ROOT, "results", "twin_residue_audit.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
