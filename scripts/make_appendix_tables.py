#!/usr/bin/env python
"""Appendix tables for the 2026-09-11 additions: one table per claim, every model,
dataset and modality word. Writes paper/iclr2027/tables/*.tex (idempotent; each
file carries the source it was generated from).

  tab_app_ladder.tex     ignore rate (1 - flip/accuracy) on the image word, per
                         interface x dataset x model, from results/master_grid.json
  tab_app_picks.tex      where correct-but-unflipped Ground-CF image answers go
                         (stale vs another modality's value), per condition x model,
                         from the --dump_picks eval files
  tab_app_stability.tex  checkpoint range of grounding (full sweep and second half)
                         per method x dataset x model, from flip_*_step_* files
  tab_app_crop.tex       MultiVENT-G full frame -> evidence crop, paired within run
  tab_app_ctmv3.tex      plain CTM vs CTM + the slot-negative data recipe, Ground-CF,
                         all models and all three modality words
  tab_app_detect.tex     procedural conflict detection with <look> and <read> only
                         (no compare word): share of conflict items on which the two
                         requests return different values, per method x dataset x model

Usage: python scripts/make_appendix_tables.py
"""
import glob, json, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper", "iclr2027", "tables")
MODELS = [("gemma3", "Gemma-3-4B", ""), ("qwen4b", "Qwen-3.5-4B", "_qwen35"),
          ("qwen2b", "Qwen-3.5-2B", "_qwen2b"), ("e4b", "Gemma-4-E4B", "_gemma4e4b")]
DS = [("vcf", "VCF"), ("color", "ColorSwap"), ("coco", "COCO-CF"), ("groundcf", "Ground-CF")]
IF = [("instr|None", "English instruction"), ("pt|5", "Prompt tuning"),
      ("pt+ctm|5", "Prompt tuning + CTM"), ("lora_r4|None", "LoRA $r{=}4$"),
      ("word_sft|5", "Neologisms, SFT"), ("word+ctm|5", "Neologisms + CTM")]
F = lambda v: "--" if v is None else f"{v:.2f}".lstrip("0") if 0 < v < 1 else f"{v:.2f}"


def head(cols, spec, caption_note):
    return ["% AUTO-GENERATED by scripts/make_appendix_tables.py -- do not edit",
            f"% {caption_note}", "\\begin{tabular}{" + spec + "}", "\\toprule",
            " & ".join(cols) + " \\\\", "\\midrule"]


def tail(lines):
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def w(name, text):
    open(os.path.join(OUT, name), "w").write(text)
    print(f"[saved] tables/{name}")


# ---------------------------------------------------------------- ladder
def ladder(g):
    lines = head(["Interface", "Model"] + [d for _, d in DS[:3]], "ll" + "c" * 3,
                 "source: results/master_grid.json, 1 - G.look/R.look at the L=5 parity cell")
    for key, lab in IF:
        for i, (m, mlab, _) in enumerate(MODELS):
            row = []
            for ds, _ in DS[:3]:
                c = g.get(f"{ds}|{m}|{key}")
                v = (100 * (1 - c["G.look"] / c["R.look"])
                     if c and c.get("R.look") and c.get("G.look") is not None else None)
                row.append("--" if v is None else f"{v:.0f}\\%")
            lines.append(f"{lab if i == 0 else ''} & {mlab} & " + " & ".join(row) + " \\\\")
        lines.append("\\addlinespace")
    return tail(lines)


# ---------------------------------------------------------------- picks
PICK_COND = [("No request", "clevr3_f_5tok_sft_seed0{s}", "flip_step_800_noop_picks.json"),
             ("English instruction", "clevr3_f_5tok_sft_seed0{s}", "flip_step_800_instr_iv5_picks.json"),
             ("Prompt tuning", "clevr3_f_pt_5tok_seed0{s}", "flip_step_800_picks.json"),
             ("LoRA $r{=}4$", "clevr3_f_lora_r4_seed0{s}", "flip_step_800_picks.json"),
             ("Neologisms, SFT", "clevr3_f_5tok_sft_seed0{s}", "flip_step_800_picks.json"),
             ("Neologisms + CTM", "clevr3_f_5tok_ctm_seed0{s}", "flip_step_800_picks.json")]


def picks():
    lines = head(["Interface", "Model", "correct", "flip", "not flipped", "stale", "other modality"],
                 "llccccc", "source: eval_clevr3_flip.py --dump_picks 1 (Ground-CF image twins, n=150)")
    for lab, run, fname in PICK_COND:
        for i, (m, mlab, sfx) in enumerate(MODELS[:2]):
            p = f"{ROOT}/runs/{run.format(s=sfx)}/eval/clevr3_test_id/{fname}"
            if not os.path.exists(p):
                lines.append(f"{lab if i == 0 else ''} & {mlab} & " + " & ".join(["--"] * 5) + " \\\\")
                continue
            pk = json.load(open(p)).get("picks", {}).get("look", [])
            corr = [x for x in pk if x["pa"] == x["gold_a"]]
            flip = [x for x in corr if x["pb"] == x["gold_b"]]
            non = [x for x in corr if x["pb"] != x["gold_b"]]
            stale = sum(x["pb"] == x["gold_a"] for x in non)
            text = sum(x["pb"] != x["gold_a"] and x["pb"] in (x["read"], x["ocr"]) for x in non)
            lines.append(f"{lab if i == 0 else ''} & {mlab} & {len(corr)} & {len(flip)} & "
                         f"{len(non)} & {stale} & {text} \\\\")
        lines.append("\\addlinespace")
    return tail(lines)


# ---------------------------------------------------------------- stability
STEPS = (100, 200, 300, 400, 500, 600, 700, 800)
SMETH = [("sft", "Neologisms, SFT"), ("ctm", "Neologisms + CTM"),
         ("pt", "Prompt tuning"), ("lora", "LoRA $r{=}4$")]
SCELL = [("vcf", "look", "VCF"), ("color", "read", "ColorSwap"),
         ("coco", "look", "COCO-CF"), ("groundcf", "read", "Ground-CF")]


def spath(ds, meth, sfx, step):
    if ds == "groundcf":
        stem = {"sft": "clevr3_f_5tok_sft_seed0", "ctm": "clevr3_f_5tok_ctm_seed0",
                "pt": "clevr3_f_pt_5tok_seed0", "lora": "clevr3_f_lora_r4_seed0"}[meth]
        return f"{ROOT}/runs/{stem}{sfx}/eval/clevr3_test_id/flip_step_{step}.json"
    stem = {"sft": f"{ds}_neo_ctrl_5tok_sft_seed0", "ctm": f"{ds}_neo_ctrl_5tok_ctm_seed0",
            "pt": f"{ds}_pt_na_5tok_sft_seed0", "lora": f"{ds}_lora_r4_lr2e4_seed0"}[meth]
    return f"{ROOT}/runs/{stem}{sfx}/eval/{ds}_test_id/flip_ll_step_{step}.json"


def stability():
    lines = head(["Method", "Model"] + [f"{d} range" for _, _, d in SCELL], "ll" + "c" * 4,
                 "source: per-step flip files; each cell = full-sweep range / second-half range / final")
    for meth, lab in SMETH:
        for i, (m, mlab, sfx) in enumerate(MODELS):
            row = []
            for ds, ch, _ in SCELL:
                ys = []
                for st in STEPS:
                    try:
                        ys.append(json.load(open(spath(ds, meth, sfx, st)))[f"{ch}_flip"])
                    except Exception:
                        pass
                ys = [y for y in ys if y is not None]
                if len(ys) < 4:
                    row.append("--"); continue
                full = max(ys) - min(ys)
                half = max(ys[len(ys) // 2:]) - min(ys[len(ys) // 2:])
                row.append(f"{F(full)} / {F(half)} / {F(ys[-1])}")
            if any(x != "--" for x in row):
                lines.append(f"{lab if i == 0 else ''} & {mlab} & " + " & ".join(row) + " \\\\")
        lines.append("\\addlinespace")
    return tail(lines)


# ---------------------------------------------------------------- crop
def crop():
    rows = []
    for f in glob.glob(f"{ROOT}/runs/*/eval/mvg_flip/flip_step_*.json"):
        run = f.split("runs/")[1].split("/")[0]; b = os.path.basename(f)
        if "qwen" in run or "smoke" in run or "clean" not in b:
            continue
        d = json.load(open(f)); vis = d.get("vis_value_swap") or {}
        if vis.get("flip") is None:
            continue
        meth = ("LoRA" if "lora" in run else "Prompt tuning" if "_pt_" in run else
                "English instruction" if "_instr" in b else "No request" if "_noop" in b
                else "Neologism + CTM")
        rows.append((meth, run, "crop" if "crop" in b else "full", vis["flip"]))
    byrun = collections.defaultdict(dict)
    for meth, run, frame, v in rows:
        byrun[(meth, run)][frame] = v
    keep = {}
    for (meth, run), v in byrun.items():
        if "full" in v and "crop" in v and (meth not in keep or v["crop"] > keep[meth][2]):
            keep[meth] = (run, v["full"], v["crop"])
    lines = head(["Method", "Run", "Full frame", "Evidence crop", "$\\Delta$"], "llccc",
                 "source: runs/*/eval/mvg_flip/flip_step_800*clean*.json, vis_value_swap.flip")
    for meth in ["No request", "English instruction", "Prompt tuning", "LoRA", "Neologism + CTM"]:
        if meth in keep:
            run, f_, c_ = keep[meth]
            lines.append(f"{meth} & \\texttt{{{run.replace('_', chr(92) + '_')}}} & {F(f_)} & {F(c_)} & {c_ - f_:+.3f} \\\\")
    return tail(lines)


# ---------------------------------------------------------------- CTM vs CTM+v3
def ctmv3():
    lines = head(["Model", "Objective and recipe", "$\\langle$look$\\rangle$",
                  "$\\langle$read$\\rangle$", "$\\langle$ocr$\\rangle$"], "ll" + "c" * 3,
                 "source: runs/clevr3_f_5tok_{sft,v3,ctm,ctmv3}_seed0*/eval/clevr3_test_id/flip_step_800.json")
    ARMS = [("sft", "SFT"), ("v3", "SFT + slot negatives"),
            ("ctm", "CTM (two sided)"), ("ctmv3", "CTM + slot negatives")]
    for m, mlab, sfx in MODELS:
        for i, (arm, alab) in enumerate(ARMS):
            p = f"{ROOT}/runs/clevr3_f_5tok_{arm}_seed0{sfx}/eval/clevr3_test_id/flip_step_800.json"
            if not os.path.exists(p):
                continue
            d = json.load(open(p))
            lines.append(f"{mlab if i == 0 else ''} & {alab} & {F(d['look_flip'])} & "
                         f"{F(d['read_flip'])} & {F(d['ocr_flip'])} \\\\")
        lines.append("\\addlinespace")
    return tail(lines)


# ---------------------------------------------------------------- detection
def detect():
    """Table from results/detection_procedural.json (scripts/detect_procedural.py):
    detection on conflict items, correct attribution, false alarms on agree items,
    and the balanced score. Every interface is scored by the same forced choice over
    the same two candidate strings, so nothing here rewards output format."""
    try:
        d = json.load(open(f"{ROOT}/results/detection_procedural.json"))["cells"]
    except Exception:
        return "% results/detection_procedural.json missing; run scripts/detect_procedural.py\n"
    order = ["No request", "English instruction", "Prompt tuning", "LoRA r=4",
             "Neologisms, SFT", "Neologisms + CTM"]
    LBL = {"LoRA r=4": "LoRA $r{=}4$"}
    lines = head(["Interface", "Model", "Dataset", "detect", "attribute", "false alarm",
                  "balanced", "$n$"], "lll" + "c" * 5,
                 "source: results/detection_procedural.json")
    for lab in order:
        first = True
        for m, mlab, _ in MODELS:
            for ds, dslab in DS[:3]:
                c = d.get(f"{lab}|{m}|{ds}")
                if not c:
                    continue
                lines.append(f"{LBL.get(lab, lab) if first else ''} & {mlab} & {dslab} & "
                             f"{F(c['detect'])} & {F(c['attrib'])} & {F(c['false'])} & "
                             f"{F(c['bal'])} & {c['n']} \\\\")
                first = False
        lines.append("\\addlinespace")
    return tail(lines)


def verdict():
    """Per-cell verdict for the two sided objective (results/objective_verdict.json)."""
    try:
        d = json.load(open(f"{ROOT}/results/objective_verdict.json"))
    except Exception:
        return "% run scripts/objective_verdict.py first\n"
    cells, eps = d["cells"], d["eps"]
    lines = head(["Dataset", "Model", "Word", "supervised", "objective", "seeds", "spread",
                  "change"], "lll" + "c" * 5,
                 f"source: results/objective_verdict.json (tie tolerance {eps})")
    for ds, dslab in DS:
        first = True
        for m, mlab, _ in MODELS:
            for ch in ("look", "read", "ocr"):
                c = cells.get(f"{ds}|{m}|{ch}")
                if not c or c.get("ctm") is None or c.get("word_sft|5") is None:
                    continue
                dv = c["ctm"] - c["word_sft|5"]
                mark = "$+$" if dv > max(eps, c["ctm_spread"] or 0) else (
                    "$-$" if -dv > max(eps, c["ctm_spread"] or 0) else "$=$")
                sp = "--" if c["ctm_spread"] is None else F(c["ctm_spread"])
                lines.append(f"{dslab if first else ''} & {mlab} & $\\langle${ch}$\\rangle$ & "
                             f"{F(c['word_sft|5'])} & {F(c['ctm'])} & {c['n_seeds_ctm']} & {sp} & "
                             f"{dv:+.2f}~{mark} \\\\")
                first = False
        lines.append("\\addlinespace")
    return tail(lines)


def main():
    g = json.load(open(f"{ROOT}/results/master_grid.json"))
    w("tab_app_verdict.tex", verdict())
    w("tab_app_ladder.tex", ladder(g))
    w("tab_app_picks.tex", picks())
    w("tab_app_stability.tex", stability())
    w("tab_app_crop.tex", crop())
    w("tab_app_ctmv3.tex", ctmv3())
    w("tab_app_detect.tex", detect())


if __name__ == "__main__":
    main()
