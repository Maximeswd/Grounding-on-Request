#!/usr/bin/env python
"""Word vs prefix on the ladder under MATCHED prompts (v1.151, 2026-09-24). CPU only, reads item logs.

(1) PRE-REGISTERED headline (STATUS v1.151): pooled matched condition. Both methods on the same four held-out texts:
      word format   (control after the caption, the word's 2 held-out carriers): word flip_ll_heldout,  prefix flip_ll_ptslot_heldout
      prefix format (control first, the prefix's 2 held-out instructions):       word flip_ll_ptfmt_heldout, prefix flip_ll_heldout
    Per item and request: mean over the two formats of the conjunctive score; method = mean over items. Paired test:
    sign-flip permutation test on per-item pooled differences (word - prefix), 200k draws, seed 0.
(2) Diagnostics: word request-first (flip_ll_reqfirst*), prefix instruction without prefix (flip_ll_noprefix*).
(3) Template-sensitivity sweep (flip_ll_sw<id>, flip_ll_noprefix_sw<id>): per template the word, the prefix and the
    frozen model (no control) on identical text; per method mean / worst case / best case / range over templates.
Scores (image request `look`; text request `read`):
    Acc  = base pick is the requested source's value
    Flip = Acc and the pick follows an edit of the requested source   (look: imgswap -> image side; read: capswap -> text side)
    Stay = Acc and the pick survives an edit of the other source      (look: capswap -> image side; read: imgswap -> text side)
Frozen / no-control rows: look and read see the same prompt, so look Acc = P(image), read Acc = P(caption).
Usage: python scripts/matched_word_vs_prefix.py [--ds coco,color,vcf] [--out results/matched_word_vs_prefix]
"""
import argparse, collections, gzip, json, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("", "Gemma-3-4B"), ("_qwen35", "Qwen-3.5-4B"), ("_qwen2b", "Qwen-3.5-2B"), ("_gemma4e4b", "Gemma-4-E4B")]
SWEEP = ["S1", "S2", "S3", "S4", "S5", "S6", "P1", "P2"]
GOLD = {"look": "i", "read": "t"}
FLIPCTX = {"look": "imgswap", "read": "capswap"}
STAYCTX = {"look": "capswap", "read": "imgswap"}


def items(run, ds, name):
    f = os.path.join(ROOT, "runs", run, "eval", f"{ds}3_test_id", f"{name}_step_800_items.jsonl.gz")
    if not os.path.exists(f):
        return None
    by = collections.defaultdict(dict)
    for l in gzip.open(f, "rt"):
        a = json.loads(l)
        if "_meta" not in a:
            by[(a["item"], a["request"])][a["ctx"]] = a
    out = {}
    for (i, rq), c in by.items():
        if "base" not in c:
            continue
        acc = c["base"]["pick"] == GOLD[rq]
        out[(i, rq)] = {"acc": float(acc),
                        "flip": float(acc and FLIPCTX[rq] in c and c[FLIPCTX[rq]]["pick"] == GOLD[rq]),
                        "stay": float(acc and STAYCTX[rq] in c and c[STAYCTX[rq]]["pick"] == GOLD[rq])}
    return out


def mean(v):
    return round(sum(v) / len(v), 4) if v else None


def signflip_p(d, draws=200000, seed=0):
    d = [x for x in d if x != 0]
    if not d:
        return 1.0
    obs = abs(sum(d)); rng = random.Random(seed); hit = 0
    for _ in range(draws):
        if abs(sum(x if rng.random() < .5 else -x for x in d)) >= obs - 1e-12:
            hit += 1
    return round((hit + 1) / (draws + 1), 5)


def summarise(it, rq, m):
    return mean([v[m] for (i, r), v in it.items() if r == rq]) if it else None


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--ds", default="coco,color,vcf")
    ap.add_argument("--out", default="results/matched_word_vs_prefix"); a = ap.parse_args()
    J = {"note": __doc__.split("\n")[0], "headline": [], "diagnostics": [], "sweep": []}
    md = ["# Word vs prefix under matched prompts (ladder, test_id, conflict items)", "",
          "Generated by `scripts/matched_word_vs_prefix.py`. Headline = the pre-registered pooled matched condition "
          "(STATUS v1.151). `--` = not evaluated yet.", ""]
    f = lambda x: "--" if x is None else f"{x:.3f}"
    for ds in a.ds.split(","):
        md += [f"## {ds}", "", "### Pooled matched headline", "",
               "| model | request | metric | word (pooled) | prefix (pooled) | word: word fmt / prefix fmt | prefix: word fmt / prefix fmt | diff | sign-flip p |",
               "|---|---|---|---|---|---|---|---|---|"]
        diag_md = ["", "### Diagnostics (image request)", "",
                   "| model | cell | Acc | Flip | Stay |", "|---|---|---|---|---|"]
        for sfx, ml in MODELS:
            W, P = f"{ds}_neo_ctrl_1tok_ctm_cp_seed0{sfx}", f"{ds}_pt_na_1tok_ctm_cp_seed0{sfx}"
            ww, wp = items(W, ds, "flip_ll_heldout"), items(W, ds, "flip_ll_ptfmt_heldout")
            pw, pp = items(P, ds, "flip_ll_ptslot_heldout"), items(P, ds, "flip_ll_heldout")
            for rq in ("look", "read"):
                for m in ("flip", "stay"):
                    row = {"dataset": ds, "model": ml, "request": rq, "metric": m,
                           "word_wordfmt": summarise(ww, rq, m), "word_prefixfmt": summarise(wp, rq, m),
                           "prefix_wordfmt": summarise(pw, rq, m), "prefix_prefixfmt": summarise(pp, rq, m)}
                    if all(x is not None for x in (ww, wp, pw, pp)):
                        ks = sorted(k for k in ww if k[1] == rq and k in wp and k in pw and k in pp)
                        wv = [(ww[k][m] + wp[k][m]) / 2 for k in ks]; pv = [(pw[k][m] + pp[k][m]) / 2 for k in ks]
                        row.update(word=mean(wv), prefix=mean(pv), diff=round(mean(wv) - mean(pv), 4),
                                   p=signflip_p([x - y for x, y in zip(wv, pv)]), n=len(ks))
                    J["headline"].append(row)
                    md.append(f"| {ml} | {rq} | {m} | {f(row.get('word'))} | {f(row.get('prefix'))} | "
                              f"{f(row['word_wordfmt'])} / {f(row['word_prefixfmt'])} | {f(row['prefix_wordfmt'])} / "
                              f"{f(row['prefix_prefixfmt'])} | {f(row.get('diff'))} | {row.get('p', '--')} |")
            for lab, run, name in (("word, own format, training template", W, "flip_ll"),
                                   ("word, own format, held-out", W, "flip_ll_heldout"),
                                   ("word BEFORE the caption, training template", W, "flip_ll_reqfirst"),
                                   ("word BEFORE the caption, held-out", W, "flip_ll_reqfirst_heldout"),
                                   ("prefix, own format, training template", P, "flip_ll"),
                                   ("prefix, own format, held-out", P, "flip_ll_heldout"),
                                   ("prefix's instruction WITHOUT prefix, training template", P, "flip_ll_noprefix"),
                                   ("prefix's instruction WITHOUT prefix, held-out", P, "flip_ll_noprefix_heldout")):
                it = items(run, ds, name)
                r = {"dataset": ds, "model": ml, "cell": lab, **{m: summarise(it, "look", m) for m in ("acc", "flip", "stay")}}
                J["diagnostics"].append(r)
                diag_md.append(f"| {ml} | {lab} | {f(r['acc'])} | {f(r['flip'])} | {f(r['stay'])} |")
        md += diag_md
        # sweep: identical text, three controls
        sw_md = ["", "### Template-sensitivity sweep (image request, Flip)", "",
                 "| model | control | " + " | ".join(["train", "held-out"] + SWEEP) + " | mean | worst | best | range |",
                 "|---|---|" + "---|" * (len(SWEEP) + 6)]
        for sfx, ml in MODELS:
            W, P = f"{ds}_neo_ctrl_1tok_ctm_cp_seed0{sfx}", f"{ds}_pt_na_1tok_ctm_cp_seed0{sfx}"
            for ctl, run, pre, own in (("word", W, "flip_ll_sw", ("flip_ll_ptfmt", "flip_ll_ptfmt_heldout")),
                                       ("prefix", P, "flip_ll_sw", ("flip_ll", "flip_ll_heldout")),
                                       ("none (frozen)", P, "flip_ll_noprefix_sw", ("flip_ll_noprefix", "flip_ll_noprefix_heldout"))):
                # train / held-out columns = the PREFIX-format texts, so every column is the same visible prompt for all three
                vals = [summarise(items(run, ds, n), "look", "flip") for n in own]
                vals += [summarise(items(run, ds, f"{pre}{s}"), "look", "flip") if not (ctl.startswith("none") and s.startswith("P"))
                         else None for s in SWEEP]
                got = [v for v in vals if v is not None]
                st = {"mean": mean(got), "worst": min(got) if got else None, "best": max(got) if got else None,
                      "range": round(max(got) - min(got), 4) if got else None, "n_templates": len(got)}
                J["sweep"].append({"dataset": ds, "model": ml, "control": ctl, "templates": ["train", "heldout"] + SWEEP,
                                   "flip_look": vals, **st})
                sw_md.append(f"| {ml} | {ctl} | " + " | ".join(f(v) for v in vals) +
                             f" | {f(st['mean'])} | {f(st['worst'])} | {f(st['best'])} | {f(st['range'])} |")
        md += sw_md + [""]
    os.makedirs(os.path.dirname(os.path.join(ROOT, a.out)), exist_ok=True)
    json.dump(J, open(os.path.join(ROOT, a.out + ".json"), "w"), indent=1)
    open(os.path.join(ROOT, a.out + ".md"), "w").write("\n".join(md) + "\n")
    print("[saved]", a.out + ".{json,md}", f"headline rows with all four files: {sum('word' in r for r in J['headline'])}/{len(J['headline'])}")


if __name__ == "__main__":
    main()
