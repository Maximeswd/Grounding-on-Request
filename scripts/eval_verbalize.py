#!/usr/bin/env python
"""Self-verbalization + synonyms + PLUG-IN evaluation (Hewitt-style, ours).

For each ctrl token: (1) generate a self-verbalization and five synonyms;
(2) PLUG-IN: replace the token with each synonym / the verbalization in the
SAME routing prompt and measure LL forced-choice routing on conflict items.
The functional test of whether the token's meaning is verbalizable:
  token routing >> best-synonym routing  -> meaning-as-use (not verbalizable)
  best synonym ~= token                  -> machine-usable synonym exists
(3) CROSS-MODEL plug-in: score the SAME phrases on a different frozen model
(--plugin_model_id) -- the machine-only-synonym transfer test across families.
Controls: the English instruction ('the image') and a filler word ('banana').
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from tqdm import tqdm
from scsrc.data import load_task, build_specs, get_image
from scsrc.tokens import trigger
from scsrc import prompts as P, score as SC, model as M
from scsrc.infer import generate
from evaluate import apply_checkpoint

COLORS = {"red","orange","yellow","green","blue","purple","pink","brown","black",
          "white","gray","grey","gold","silver","tan","beige","violet","cyan",
          "maroon","navy"}


def norm(k):
    return {str(o).split("|")[0].strip().lower(): str(v).strip().lower()
            for o, v in (k or {}).items()}


def routing_acc(model, proc, ds, specs, phrase, op_want, task, max_n, is_vcf):
    hits, seen = [], 0
    for sp in specs:
        ik, tk = norm(sp.image_key), norm(sp.text_key)
        if not ik or set(ik) != set(tk):
            continue
        conf = [o for o in ik if ik[o] != tk[o]
                and not (is_vcf and any(c in o.split() for c in COLORS))]
        if not conf:
            continue
        if seen >= max_n:
            break
        seen += 1
        obj = conf[seen % len(conf)]   # per-object (multi-object ColorSwap)
        u = P.render_ctrl(P.CTRL_CANONICAL, phrase, sp.fed_caption)
        ci = P.fmt_key_task({obj: ik[obj]}, task)
        ct = P.fmt_key_task({obj: tk[obj]}, task)
        img = get_image(ds, sp)
        li, _, _ = SC.loglik(model, proc, img, u, ci, "cuda")
        lt, _, _ = SC.loglik(model, proc, img, u, ct, "cuda")
        hits.append(int((li > lt) == (op_want == "look")))
    return round(sum(hits) / max(len(hits), 1), 3), seen


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run_dir", required=True)
    ap.add_argument("--data_dir", default="data/vcf")
    ap.add_argument("--split", default="test_id")
    ap.add_argument("--step", type=int, default=800)
    ap.add_argument("--max_n", type=int, default=60)
    ap.add_argument("--plugin_model_id", default=None,
                    help="score plug-in phrases on THIS frozen model instead "
                         "(cross-family machine-only-synonym transfer); the "
                         "verbalizations are still generated by the run's model")
    ap.add_argument("--phrases_json", default=None,
                    help="skip generation; plug in these saved phrases")
    a = ap.parse_args()

    outd = os.path.join(a.run_dir, "eval", "verbalize"); os.makedirs(outd, exist_ok=True)
    ops = ("look", "read")
    phrases = {}
    if a.phrases_json:
        phrases = json.load(open(a.phrases_json))["phrases"]
        model = proc = None
    else:
        model, proc, meta, forbid = apply_checkpoint(a.run_dir, a.step, "cuda")
        n = meta["n_tokens"]
        for op in ops:
            trig = trigger(f"{op}_ctrl", n)
            verb = generate(model, proc, None, P.VERBALIZE_CTRL.format(op=trig),
                            "cuda", 60, forbid_ids=forbid)
            syn = generate(model, proc, None, P.SYNONYMS_CTRL.format(op=trig),
                           "cuda", 60, forbid_ids=forbid)
            syns = [w.strip(" .") for w in syn.replace("\n", ",").split(",")
                    if 0 < len(w.strip(" .")) < 30][:5]
            phrases[op] = {"verbalization": verb.strip()[:200], "synonyms": syns}
            print(f"[{op}] verbalization: {verb.strip()[:120]!r}")
            print(f"[{op}] synonyms: {syns}")
        json.dump({"phrases": phrases},
                  open(os.path.join(outd, f"phrases_step_{a.step}.json"), "w"), indent=1)

    # plug-in scoring model: the run's model (default) or a frozen other-family one
    if a.plugin_model_id:
        model, proc = M.load(model_id=a.plugin_model_id)
        model.eval()
    assert model is not None, "--phrases_json requires --plugin_model_id"

    ds = load_task(a.data_dir, a.split)
    specs = [s for s in build_specs(ds, a.split, conditions=("conflict",))
             if s.cond == "conflict"]
    is_vcf = "vcf" in a.data_dir
    res = {}
    for op in ops:
        rows = {}
        cands = ([("token", trigger(f"{op}_ctrl", meta["n_tokens"]))]
                 if not a.plugin_model_id else [])
        cands += [(f"syn{i}", s) for i, s in enumerate(phrases[op]["synonyms"])]
        cands += [("verbalization", phrases[op]["verbalization"][:80]),
                  ("english", "image" if op == "look" else "caption"),
                  ("filler", "banana")]
        for name, ph in tqdm(cands, desc=f"plugin({op})"):
            acc, seen = routing_acc(model, proc, ds, specs, ph, op, "color",
                                    a.max_n, is_vcf)
            rows[name] = {"phrase": str(ph)[:60], "routing": acc}
        res[op] = rows
        best_syn = max((v["routing"] for k, v in rows.items() if k.startswith("syn")),
                       default=None)
        print(f"[{op}] token={rows.get('token',{}).get('routing')} best_syn={best_syn} "
              f"english={rows['english']['routing']} filler={rows['filler']['routing']}")

    tag = (a.plugin_model_id or "self").split("/")[-1]
    out = {"run": os.path.basename(a.run_dir), "data": os.path.basename(a.data_dir),
           "split": a.split, "plugin_model": tag, "results": res}
    json.dump(out, open(os.path.join(outd, f"plugin_{tag}_step_{a.step}.json"), "w"),
              indent=1)
    print(f"[saved] {outd}/plugin_{tag}_step_{a.step}.json")


if __name__ == "__main__":
    main()
