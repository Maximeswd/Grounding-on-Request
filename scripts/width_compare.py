#!/usr/bin/env python
"""Width comparison L=1 vs L=5 for every interface that has a width (LoRA and the
untrained baselines have none). Paired over cells present at BOTH widths.
Writes results/width_compare.json (bank for the audit) and
paper/iclr2027/tables/tab_width_compare.tex (pooled acc/flip/stay per word at both
widths, plus the objective tallies at both widths).
Usage: python scripts/width_compare.py
"""
import json, os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper", "iclr2027", "tables")
DS = ["vcf", "color", "coco", "groundcf"]
MOD = ["gemma3", "qwen4b", "qwen2b", "e4b"]
WORDS = ["look", "read"]
IF = [("pt", "Prompt tuning"), ("pt+apo", "Prompt tuning + APO"), ("pt+ctm", "Prompt tuning + CTM"), ("pti", "Prompt tuning (inserted)"),
      ("word_sft", "Neologism"), ("word+v3", "Neologism + SN"), ("word+apo", "Neologism + APO"),
      ("word+vgm", "Neologism + VGM"), ("word+ctm", "Neologism + CTM"), ("word+ctm+v3", "Neologism + CTM + SN")]
TOL = .02
F = lambda v: "--" if v is None else (f"{v:.2f}".lstrip("0") if 0 < v < 1 else f"{v:.2f}")


def main():
    g = json.load(open(f"{ROOT}/results/master_grid.json"))
    cell = lambda ds, m, meth, L, k, w: (g.get(f"{ds}|{m}|{meth}|{L}") or {}).get(
        "R.looktwin" if (ds, k, w) == ("groundcf", "R", "look") else f"{k}.{w}")
    bank = {"note": "paired over cells present at both L=1 and L=5; pooled = mean over paired cells. tallies: fixed tol .02 on the grid cell (single seed), NOT the seed-spread rule of objective_verdict.py; do not print next to the 18/0/18 verdict", "interfaces": {}, "tallies": {}, "ctm_by_dataset": {}}
    rows = []
    for meth, lab in IF:
        rec = {"n": {}, "pooled": {}, "flip_delta": {}}
        for w in WORDS:
            pairs = [(cell(ds, m, meth, "1", "G", w), cell(ds, m, meth, "5", "G", w), ds, m) for ds in DS for m in MOD]
            pairs = [p for p in pairs if p[0] is not None and p[1] is not None]
            rec["n"][w] = len(pairs)
            for k in ("R", "G", "Sc"):
                for L in ("1", "5"):
                    v = [cell(ds, m, meth, L, k, w) for _, _, ds, m in pairs]
                    v = [x for x in v if x is not None]
                    rec["pooled"][f"{k}.{w}.L{L}"] = sum(v) / len(v) if v else None
            if pairs:
                d = [b - a for a, b, _, _ in pairs]
                rec["flip_delta"][w] = {"mean_L5_minus_L1": sum(d) / len(d),
                                        "L5_better": sum(b > a + TOL for a, b, _, _ in pairs),
                                        "L1_better": sum(a > b + TOL for a, b, _, _ in pairs)}
        bank["interfaces"][meth] = rec
        if sum(rec["n"].values()) == 0:
            continue
        cells = []
        for w in WORDS:
            for k in ("R", "G", "Sc"):
                cells += [F(rec["pooled"][f"{k}.{w}.L1"]), F(rec["pooled"][f"{k}.{w}.L5"])]
        rows.append(f"{lab} & {rec['n']['look']}/{rec['n']['read']} & " + " & ".join(cells) + " \\\\")
    # objective tallies at both widths (paired within width)
    for name, a_m, b_m in [("ctm_vs_sft", "word_sft", "word+ctm"), ("ctm_vs_apo", "word+apo", "word+ctm"), ("apo_vs_sft", "word_sft", "word+apo")]:
        for L in ("1", "5"):
            win = lose = tie = 0
            for ds in DS:
                for m in MOD:
                    for w in WORDS:
                        a, b = cell(ds, m, a_m, L, "G", w), cell(ds, m, b_m, L, "G", w)
                        if a is None or b is None:
                            continue
                        delta = round(b - a, 12)
                        if delta > TOL:
                            win += 1
                        elif delta < -TOL:
                            lose += 1
                        else:
                            tie += 1
            bank["tallies"][f"{name}.L{L}"] = {"better": win, "worse": lose, "tie": tie}
    for ds in DS:
        for w in WORDS:
            for L in ("1", "5"):
                v = [cell(ds, m, "word+ctm", L, "G", w) for m in MOD]
                v = [x for x in v if x is not None]
                bank["ctm_by_dataset"][f"{ds}.{w}.L{L}"] = sum(v) / len(v) if v else None
    json.dump(bank, open(f"{ROOT}/results/width_compare.json", "w"), indent=1)
    head = ["% AUTO-GENERATED by scripts/width_compare.py from results/master_grid.json -- do not edit",
            "% pooled over the cells present at both widths (n cells look/read); L1 = one embedding row, L5 = five",
            "\\begin{tabular}{lr" + "cc" * 6 + "}", "\\toprule",
            " & & \\multicolumn{6}{c}{\\lk{}} & \\multicolumn{6}{c}{\\rdw{}} \\\\",
            "\\cmidrule(lr){3-8}\\cmidrule(lr){9-14}",
            " & & \\multicolumn{2}{c}{Acc.} & \\multicolumn{2}{c}{Flip} & \\multicolumn{2}{c}{Stay} & \\multicolumn{2}{c}{Acc.} & \\multicolumn{2}{c}{Flip} & \\multicolumn{2}{c}{Stay} \\\\",
            "Interface & $n$ & " + " & ".join(["L1 & L5"] * 6) + " \\\\", "\\midrule"]
    # tallies stay in the JSON only: they use a fixed .02 tolerance on single seeds, not the
    # seed-spread rule of scripts/objective_verdict.py that the paper prints (18/0/18 at L=5).
    tail = ["\\bottomrule", "\\end{tabular}"]
    open(f"{OUT}/tab_width_compare.tex", "w").write("\n".join(head + rows + tail) + "\n")
    print(f"[saved] tab_width_compare.tex ({len(rows)} interfaces); results/width_compare.json")
    for k, v in bank["tallies"].items():
        print(f"  {k:14s} {v}   (fixed .02 rule, single seed)")


if __name__ == "__main__":
    main()
