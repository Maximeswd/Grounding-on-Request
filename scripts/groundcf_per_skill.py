#!/usr/bin/env python
"""Ground-CF by attribute (v1.173, 2026-09-24). CPU only, read-only.
Accuracy / Flip / Stay per model x method x attribute (count, colour, shape, spatial) x request, from the per_skill
blocks of the headline evaluation files (the same files as the main-grid cells). Accuracy = correct on the original
context; Flip = correct AND follows the requested source's edit; Stay = correct AND unchanged under the competing edit
(conjunctive). Flip and Stay are conjunctions with Accuracy, so they cannot exceed it on the same items; the gap is the
information. Trained methods: held-out questions (`_cp4_ho`); no request / English: training question phrasings
(`_cp4_fc_noop`, `_cp4_fc_instr`, INSTR_VARIANT=5) -- the question sets differ, flagged in the output.
Writes results/groundcf_per_skill.{json,md}. Usage: python scripts/groundcf_per_skill.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("", "Gemma-3"), ("_qwen35", "Qwen-4B"), ("_qwen2b", "Qwen-2B")]
METHODS = [("No request (held-out q)", "clevr3_2s_5tok_sft_seed0{s}", "_cp4_ho_fc_noop"), ("English (held-out q)", "clevr3_2s_5tok_sft_seed0{s}", "_cp4_ho_fc_instr"),
           ("No request*", "clevr3_2s_5tok_sft_seed0{s}", "_cp4_fc_noop"), ("English*", "clevr3_2s_5tok_sft_seed0{s}", "_cp4_fc_instr"),
           ("Prefix L1", "clevr3_2s_pt_1tok_ctm_cp_fc_seed0{s}", "_cp4_ho"),
           ("LoRA r16", ("clevr3_2s_lora_r16_ctm_cp_fc_look_seed0{s}", "clevr3_2s_lora_r16_ctm_cp_fc_read_seed0{s}"), "_cp4_ho"),
           ("Word L1", "clevr3_2s_1tok_ctm_cp_fc_seed0{s}", "_cp4_ho"),
           # v1.190 early word (--gcf_word_pos first) at its own position, and moved to the original word's late slot
           ("Word L1, early", "clevr3_2s_1tok_ctm_cp_fc_pfirst_seed0{s}", "_cp4_ho_reloc_first"),
           ("Word L1, early, moved late", "clevr3_2s_1tok_ctm_cp_fc_pfirst_seed0{s}", "_cp4_ho"),
           ("Word L1, SFT only", "clevr3_2s_1tok_sft_fc_seed0{s}", "_cp4_ho"),
           ("LoRA r16 joint", "clevr3_2s_lora_r16_ctm_cp_fc_joint_seed0{s}", "_cp4_ho")]
SKILLS = [("all", "all"), ("color", "colour"), ("object", "shape"), ("count", "count"), ("spatial", "spatial")]


SPLIT = "test_id"


def get(run, tag):
    f = os.path.join(ROOT, "runs", run, "eval", f"clevr3_{SPLIT}", f"flip_step_800{tag}.json")
    return json.load(open(f)) if os.path.exists(f) else None


def cell(d, sk, req):
    if d is None:
        return None
    src = d if sk == "all" else (d.get("per_skill") or {}).get(sk) or {}
    return tuple(src.get(f"{req}_{m}") for m in ("acc", "flip", "stay_c"))


def main_split():
    bank, md = {}, [f"# Ground-CF by attribute: Accuracy / Flip / Stay -- {SPLIT}", "",
                    "Generated by `scripts/groundcf_per_skill.py`. * = training question phrasings (other rows: held-out). "
                    "Stay = correct and unchanged under the competing edit. count: Flip over the 146 of 187 items with an image twin.", ""]
    for req in ("look", "read"):
        md += [f"## <{req}>", "", "| attribute | method | " + " | ".join(m for _, m in MODELS) + " |", "|---|---|---|---|---|"]
        for sk, skn in SKILLS:
            for lab, run, tag in METHODS:
                cells = []
                for sfx, ml in MODELS:
                    if isinstance(run, tuple):                         # LoRA: one adapter per request
                        d = get(run[0 if req == "look" else 1].format(s=sfx), tag)
                    else:
                        d = get(run.format(s=sfx), tag)
                    c = cell(d, sk, req); bank[f"{req}|{skn}|{lab}|{ml}"] = c
                    fx = lambda x: "-" if x is None else ("1.0" if round(x, 2) >= 1 else f"{x:.2f}"[1:])
                    cells.append("pending" if c is None or c[0] is None else "/".join(fx(x) for x in c))
                md.append(f"| {skn} | {lab} | " + " | ".join(cells) + " |")
        md.append("")
    return bank, md


def main():
    global SPLIT
    allb, allmd = {}, []
    for SPLIT in ("test_id", "test_ood"):          # v1.183 (author): ID and OOD stored side by side
        b, md = main_split(); allb[SPLIT] = b; allmd += md + [""]
    json.dump(allb, open(os.path.join(ROOT, "results", "groundcf_per_skill.json"), "w"), indent=1)
    open(os.path.join(ROOT, "results", "groundcf_per_skill.md"), "w").write("\n".join(allmd) + "\n")
    print("\n".join(allmd))


if __name__ == "__main__":
    main()
