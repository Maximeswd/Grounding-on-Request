#!/usr/bin/env python
"""Ground-CF held cells (v1.190, 2026-09-25, author). CPU only, read-only.
Every trained Ground-CF control (word, early word, prefix, LoRA specialists, joint LoRA) is trained with
--held_cells look:spatial,read:count: the IMAGE request never trains on spatial questions and the CAPTION request never
trains on count questions. Both attribute families ARE trained -- spatial with <read>, count with <look> -- so the held
cells are request x attribute COMBINATIONS, and their test numbers measure transfer of a request to an attribute it was
only ever trained on with the other request, not ordinary IID performance.
Per model x method x split: Acc / Flip / Stay on the held cell and on the mean of the three trained cells, the
four-attribute mean the grid reports (macro over attributes), and the gain over English on the same cell (English and no
request are untrained, so for them the split is only a difficulty reference).
Writes results/groundcf_held_cells.{md,json}. Usage: python scripts/groundcf_held_cells.py
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import correctness_vs_control as C  # noqa: E402

HELD = {"look": "spatial", "read": "count"}
SKILLS = ("color", "object", "count", "spatial")
METHODS = [("No request", None), ("English", None), ("Prefix L1", None), ("LoRA r16", None), ("Word L1", None),
           ("Word L1, early", ("clevr3_2s_1tok_ctm_cp_fc_pfirst_seed0{s}", "_cp4_ho_reloc_first"))]


def per_skill(rows):
    out = {}
    for sk in SKILLS:
        R = [r for r in rows if r["skill"] == sk]
        if not R:
            continue
        fv = [r["flip"] for r in R if r["flip"] is not None]; sv = [r["stay"] for r in R if r["stay"] is not None]
        out[sk] = (sum(r["ok0"] for r in R) / len(R), sum(fv) / len(fv) if fv else None, sum(sv) / len(sv) if sv else None)
    return out


def rows_for(meth, spec, sfx, split):
    if spec is None:
        return C.gcf_items(sfx, meth, split)
    run, tag = spec
    f = os.path.join(ROOT, "runs", run.format(s=sfx), "eval", f"clevr3_{split}", f"flip_step_800{tag}.json")
    if not os.path.exists(f):
        return {"look": None, "read": None}
    # same record logic as correctness_vs_control.gcf_items, pointed at another file
    d = json.load(open(f)); out = {}
    for req in ("look", "read"):
        rows = []
        for x in (d.get("picks") or {}).get(req) or []:
            g = x["gold"]; ok0 = x.get("p0") == g["base"]
            if req == "look":
                fl = None if x.get("p_twin") is None else (ok0 and x["p_twin"] == g["twin"])
                st = None if x.get("p_capedit") is None else (ok0 and x["p_capedit"] == g["capedit"])
            else:
                fl = None if x.get("p1") is None else (ok0 and x["p1"] == g["capedit"])
                st = None if x.get("p_twin") is None else (ok0 and x["p_twin"] == g["twin"])
            rows.append({"skill": x.get("skill"), "ok0": ok0, "flip": fl, "stay": st})
        out[req] = rows or None
    return out


def f3(x):
    return "-" if x is None else ("1.0" if round(x, 3) >= 1 else f"{x:.3f}"[1:] if x >= 0 else f"−{abs(x):.3f}"[0] + f"{abs(x):.3f}"[1:])


def main():
    bank, md = {}, ["# Ground-CF held cells: <look> × spatial and <read> × count", "",
                    "Generated by `scripts/groundcf_held_cells.py`. Trained controls never see these request × attribute "
                    "combinations; each attribute family is trained with the other request. Cells: Acc / Flip / Stay. "
                    "'trained' = mean of the three trained attributes; 'grid' = mean of all four (what the grid reports). "
                    "Δ Flip vs English = method − English on the same cell (held | trained).", ""]
    for split in ("test_id", "test_ood"):
        sl = "ID" if split == "test_id" else "OOD"
        for req in ("look", "read"):
            h = HELD[req]
            md += [f"## {sl}, <{req}> (held attribute: {h})", "",
                   "| model | method | held cell | trained cells (mean) | grid (4-attr mean) | Δ Flip vs English: held \\| trained |",
                   "|---|---|---|---|---|---|"]
            for sfx, ml in C.MODELS:
                eng = None
                for meth, spec in METHODS:
                    R = rows_for(meth, spec, sfx, split).get(req)
                    if not R:
                        md.append(f"| {ml} | {meth} | pending | | | |"); continue
                    ps = per_skill(R)
                    if h not in ps:
                        continue
                    tr = [ps[s] for s in SKILLS if s != h and s in ps]
                    tm = tuple(sum(t[i] for t in tr) / len(tr) if all(t[i] is not None for t in tr) else None for i in range(3))
                    al = tuple(sum(ps[s][i] for s in ps) / len(ps) if all(ps[s][i] is not None for s in ps) else None for i in range(3))
                    if meth == "English":
                        eng = (ps[h][1], tm[1])
                    dl = ("-" if eng is None or meth in ("No request", "English") or None in (ps[h][1], tm[1], eng[0], eng[1])
                          else f"{ps[h][1] - eng[0]:+.3f} \\| {tm[1] - eng[1]:+.3f}")
                    bank[f"{sl}|{req}|{ml}|{meth}"] = {"held": ps[h], "trained_mean": tm, "grid_mean": al, "per_skill": ps}
                    c = lambda t: "/".join(f3(x) for x in t)
                    md.append(f"| {ml} | {meth} | {c(ps[h])} | {c(tm)} | {c(al)} | {dl} |")
            md.append("")
    json.dump(bank, open(os.path.join(ROOT, "results", "groundcf_held_cells.json"), "w"), indent=1)
    open(os.path.join(ROOT, "results", "groundcf_held_cells.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
